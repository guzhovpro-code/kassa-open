"""Категория записи по тексту «на что». Только словарь и регулярные выражения, без LLM.

Порядок проверки: первое совпадение выигрывает («AI-подписка» раньше «обучения»: «курсор» - не «курсы»).
- текст приводится к нижнему регистру и «ё» -> «е», поэтому в шаблонах только «е»;
- «бар» ищется как слово (\\bбар ловил бы «барбершоп»);
- «жильё» включает ЖКХ, квартплату, электричество;
- есть категории «подарки» и «транспорт».
Не распознали - «прочее» (расход) или «доход» (поступление): запись не блокируется.
"""
import re

DEFAULT_OUT = "прочее"
DEFAULT_IN = "доход"

# Порядок важен. (категория, шаблон по тексту в нижнем регистре, «ё» заменена на «е»)
_RULES = [
    ("AI-подписка", r"клод|claude|gpt|курсор|cursor|anthropic|openai|codex|нейросет"),
    ("продукты", r"продукт|магазин|пятерочк|маркет|супермаркет|мигрос|migros|овощ|фрукт|рынок|хлеб|булоч|пекарн"
                 r"|выпечк|бакалея"),
    ("кафе", r"кофе|кафе|ресторан|обед|ужин|завтрак|ланч|пицц|суши|бургер|шаурм|столов|роллы"),
    ("бар", r"\bбар(?:а|е|у|ы|ов|ом)?\b|пиво|пива|коктейл|паб"),
    ("развлечения", r"аквапарк|пляж|кино(?!а|лог)|боулинг|аттракцион|картинг|развлечен|лунапарк"),
    ("топливо", r"заправ|бензин|топлив|дизел|солярк"),
    ("транспорт", r"такси|taxi|\buber\b|\bубер\b|\bbolt\b|\bметро\b|автобус|трамвай|маршрутк|проезд|парковк|каршеринг"
                  r"|самокат"),
    ("быт", r"\bбыт|аптек|лекарств|хозяйств|стирал|моющ"),
    ("жильё", r"аренд|квартир|жиль|коммунал|айдат|ипотек|жкх|квартплат|электричеств"),
    ("подарки", r"подар|букет|цветы|цветов"),
    ("семья", r"семья|семье|семью|семьи|семейн|\bсын|детск|ребен|игрушк"),
    ("обучение", r"обучен|курс|школ|учеб|универ|репетитор|экзамен"),
    ("перевод", r"перевод"),
]
_COMPILED = [(name, re.compile(pattern)) for name, pattern in _RULES]
_INCOME_RETURN = re.compile(r"возврат|вернул|кешбэк|кэшбэк|cashback")

# Для выпадающего списка (порядок для глаза, не порядок проверки). Тест следит, чтобы все категории словаря были тут.
OUT_CATEGORIES = ["продукты", "кафе", "бар", "развлечения", "топливо", "транспорт", "быт", "жильё", "подарки",
                  "семья", "обучение", "перевод", "AI-подписка", DEFAULT_OUT]
IN_CATEGORIES = ["доход", "возврат", "другое"]


def _norm(text) -> str:
    return " ".join(str(text or "").split()).lower().replace("ё", "е")


def categorize(text, direction: str) -> str:
    """Категория по тексту «на что». direction: 'out' или 'in'. Пустой и нераспознанный текст -> умолчание."""
    low = _norm(text)
    if direction == "in":
        return "возврат" if _INCOME_RETURN.search(low) else DEFAULT_IN
    for name, rx in _COMPILED:
        if rx.search(low):
            return name
    return DEFAULT_OUT
